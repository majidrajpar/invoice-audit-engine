"""
Excel Report Generator for Invoice and Receipt Audit Ingestion.

Generates a multi-tab, professionally formatted audit workbook:
1. Executive_Summary: Batch KPIs, pass/rejection rates, manual triage counts.
2. Invoice_Register: Header-level details, document type, confidence flagging.
3. Line_Item_Detail: Trench-level items with automated Qty x Rate math & <70% confidence triage.
4. Price_Variance_Analytics: Procurement intelligence detecting unit price variances.
5. Audit_Exceptions: Prioritized queue for math errors, tax compliance, and low-confidence triage.
"""

import os
import re
from collections import defaultdict
from typing import List, Dict, Any, Tuple
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

from .schema import InvoiceExtractionResult

NAVY_HEADER = "1B365D"
WHITE_TEXT = "FFFFFF"
LIGHT_RED = "FFD9D9"
DARK_RED = "900000"
LIGHT_GREEN = "D9EAD3"
DARK_GREEN = "274E13"
AMBER_FILL = "FCE5CD"
LIGHT_YELLOW = "FFF2CC"
DARK_YELLOW = "7F6000"
BORDER_GRAY = "D3D3D3"

CONFIDENCE_THRESHOLD = 0.70

def normalize_desc(desc: str) -> str:
    """Normalizes item description for procurement benchmarking."""
    if not desc:
        return "Unknown"
    cleaned = re.sub(r"[^\w\s]", "", desc).strip().lower()
    return " ".join(cleaned.split())

def export_audit_to_excel(
    results: List[InvoiceExtractionResult],
    output_path: str
) -> str:
    """Exports InvoiceExtractionResults to a structured Excel audit workbook."""
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    wb = openpyxl.Workbook()
    wb.properties.creator = "Majid Mumtaz (CIA, ACA, FCCA)"
    wb.properties.title = "Continuous Controls Monitoring - Master Invoice Audit Register"
    wb.properties.subject = "Continuous Document Telemetry & Mathematical Reconciliation"
    wb.properties.description = "Generated by Invoice Audit Engine (MIT License) | Majid Mumtaz"

    header_font = Font(name="Calibri", size=11, bold=True, color=WHITE_TEXT)
    header_fill = PatternFill(start_color=NAVY_HEADER, end_color=NAVY_HEADER, fill_type="solid")
    title_font = Font(name="Calibri", size=14, bold=True, color=NAVY_HEADER)
    subtitle_font = Font(name="Calibri", size=10, italic=True, color="555555")
    bold_font = Font(name="Calibri", size=10, bold=True)
    regular_font = Font(name="Calibri", size=10)

    thin_border = Border(
        left=Side(style='thin', color=BORDER_GRAY),
        right=Side(style='thin', color=BORDER_GRAY),
        top=Side(style='thin', color=BORDER_GRAY),
        bottom=Side(style='thin', color=BORDER_GRAY)
    )

    pass_fill = PatternFill(start_color=LIGHT_GREEN, end_color=LIGHT_GREEN, fill_type="solid")
    pass_font = Font(name="Calibri", size=10, bold=True, color=DARK_GREEN)
    fail_fill = PatternFill(start_color=LIGHT_RED, end_color=LIGHT_RED, fill_type="solid")
    fail_font = Font(name="Calibri", size=10, bold=True, color=DARK_RED)
    warn_fill = PatternFill(start_color=LIGHT_YELLOW, end_color=LIGHT_YELLOW, fill_type="solid")
    warn_font = Font(name="Calibri", size=10, bold=True, color=DARK_YELLOW)
    triage_fill = PatternFill(start_color=AMBER_FILL, end_color=AMBER_FILL, fill_type="solid")
    triage_font = Font(name="Calibri", size=10, bold=True, color="B45F06")

    # ----------------------------------------------------
    # TAB 1: EXECUTIVE SUMMARY
    # ----------------------------------------------------
    ws_summary = wb.active
    ws_summary.title = "Executive_Summary"
    ws_summary.views.sheetView[0].showGridLines = True

    ws_summary["A1"] = "INTERNAL AUDIT CONTINUOUS MONITORING: INVOICE & RECEIPT INGESTION"
    ws_summary["A1"].font = title_font

    ws_summary["A2"] = "Continuous Controls Monitoring (CCM) Telemetry | Architect: Majid Mumtaz (CIA, ACA, FCCA) | MIT License"
    ws_summary["A2"].font = subtitle_font

    total_docs = len(results)
    passed_docs = sum(1 for r in results if r.quality_passed and r.is_invoice_archetype)
    excluded_docs = sum(1 for r in results if r.quality_passed and not r.is_invoice_archetype)
    rejected_docs = sum(1 for r in results if not r.quality_passed)
    math_failures = sum(1 for r in results if r.quality_passed and r.is_invoice_archetype and not r.audit_flags.is_mathematically_sound)
    tax_no_trn = sum(1 for r in results if r.quality_passed and r.is_invoice_archetype and r.audit_flags.missing_tax_id_on_taxed_invoice)
    line_item_calc_mismatches = sum(r.audit_flags.line_item_calc_mismatches_count for r in results if r.quality_passed and r.is_invoice_archetype)
    low_conf_docs = sum(1 for r in results if r.quality_passed and r.is_invoice_archetype and r.average_ocr_confidence < CONFIDENCE_THRESHOLD)

    total_spend = sum((r.totals.total_amount or 0.0) for r in results if r.quality_passed and r.is_invoice_archetype and r.totals)
    total_tax = sum((r.totals.tax_amount or 0.0) for r in results if r.quality_passed and r.is_invoice_archetype and r.totals)

    metrics = [
        ("Total Documents Examined", total_docs, "#,##0"),
        ("Clean Invoices Audited", passed_docs, "#,##0"),
        ("Non-Invoice Documents Filtered & Excluded", excluded_docs, "#,##0"),
        ("Documents Rejected at Ingestion Gate", rejected_docs, "#,##0"),
        ("Documents Requiring Manual Review (Confidence < 70%)", low_conf_docs, "#,##0"),
        ("Mathematical Reconciliation Failures (Totals)", math_failures, "#,##0"),
        ("Line-Item Arithmetic Mismatches (Qty x Rate)", line_item_calc_mismatches, "#,##0"),
        ("Tax Billed Without TRN / Tax ID", tax_no_trn, "#,##0"),
        ("Total Billed Spend Audited", total_spend, "#,##0.00"),
        ("Total Billed Tax Audited", total_tax, "#,##0.00")
    ]

    ws_summary["A4"] = "Batch KPI Metric"
    ws_summary["B4"] = "Value"
    ws_summary["A4"].font = header_font
    ws_summary["A4"].fill = header_fill
    ws_summary["B4"].font = header_font
    ws_summary["B4"].fill = header_fill

    for idx, (label, val, num_fmt) in enumerate(metrics, start=5):
        ws_summary[f"A{idx}"] = label
        ws_summary[f"B{idx}"] = val
        ws_summary[f"A{idx}"].font = bold_font if "Total Billed" in label else regular_font
        ws_summary[f"B{idx}"].font = bold_font
        ws_summary[f"B{idx}"].number_format = num_fmt
        ws_summary[f"A{idx}"].border = thin_border
        ws_summary[f"B{idx}"].border = thin_border

        if label in ["Documents Rejected at Ingestion Gate", "Mathematical Reconciliation Failures (Totals)", "Line-Item Arithmetic Mismatches (Qty x Rate)", "Tax Billed Without TRN / Tax ID"] and val > 0:
            ws_summary[f"B{idx}"].fill = fail_fill
            ws_summary[f"B{idx}"].font = fail_font
        elif label == "Non-Invoice Documents Filtered & Excluded" and val > 0:
            ws_summary[f"B{idx}"].fill = warn_fill
            ws_summary[f"B{idx}"].font = warn_font
        elif label == "Documents Requiring Manual Review (Confidence < 70%)" and val > 0:
            ws_summary[f"B{idx}"].fill = triage_fill
            ws_summary[f"B{idx}"].font = triage_font

    # ----------------------------------------------------
    # TAB 2: INVOICE REGISTER
    # ----------------------------------------------------
    ws_reg = wb.create_sheet(title="Invoice_Register")
    ws_reg.views.sheetView[0].showGridLines = True

    # Declarative column definitions: (Header, NumFormat)
    reg_columns: List[Tuple[str, Optional[str]]] = [
        ("File Name", None),
        ("Quality Status", None),
        ("Doc Type", None),
        ("Invoice #", None),
        ("PO #", None),
        ("Invoice Date", None),
        ("Due Date", None),
        ("Vendor Name", None),
        ("Currency", None),
        ("Subtotal", "#,##0.00"),
        ("Discount", "#,##0.00"),
        ("Tax Rate %", "0.0%"),
        ("Tax Amount", "#,##0.00"),
        ("Total Amount", "#,##0.00"),
        ("Tax ID / TRN", None),
        ("Math Reconciled?", None),
        ("Totals Variance", "#,##0.00"),
        ("Lines Variance", "#,##0.00"),
        ("Missing TRN Alert", None),
        ("OCR Confidence", "0.0%"),
        ("Manual Review Required?", None),
        ("Audit Exceptions / Lineage", None),
        ("SHA-256 Hash", None)
    ]

    ws_reg.append([col[0] for col in reg_columns])
    for col_idx in range(1, len(reg_columns) + 1):
        cell = ws_reg.cell(row=1, column=col_idx)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center", vertical="center")

    for r in results:
        fname = os.path.basename(r.file_path)
        if not r.quality_passed:
            status = "REJECTED"
        elif not r.is_invoice_archetype:
            status = f"EXCLUDED ({r.document_type})"
        else:
            status = "PASSED"

        h = r.header
        tot = r.totals
        af = r.audit_flags

        needs_review = "NO"
        if r.quality_passed:
            if not r.is_invoice_archetype:
                needs_review = "NO (Excluded)"
            elif r.average_ocr_confidence < CONFIDENCE_THRESHOLD:
                needs_review = "YES (< 70% Conf)"
            elif not af.is_mathematically_sound or af.missing_tax_id_on_taxed_invoice:
                needs_review = "YES (Exception)"

        math_reconciled = "N/A"
        if r.quality_passed:
            if not r.is_invoice_archetype:
                math_reconciled = "N/A (Excluded)"
            elif af.is_mathematically_sound:
                math_reconciled = "YES"
            else:
                math_reconciled = "NO"

        row_data = [
            fname,
            status,
            r.document_type,
            h.invoice_number if h else "N/A",
            h.po_number if h else "N/A",
            h.invoice_date if h else "N/A",
            h.due_date if h else "N/A",
            h.vendor_name if h else "N/A",
            h.currency if h else "USD",
            tot.subtotal if (tot and r.is_invoice_archetype) else None,
            tot.discount if (tot and r.is_invoice_archetype) else None,
            tot.tax_rate_pct if (tot and r.is_invoice_archetype) else None,
            tot.tax_amount if (tot and r.is_invoice_archetype) else None,
            tot.total_amount if (tot and r.is_invoice_archetype) else None,
            h.tax_id if h else "N/A",
            math_reconciled,
            af.totals_discrepancy_amount if (r.quality_passed and r.is_invoice_archetype) else None,
            af.lines_discrepancy_amount if (r.quality_passed and r.is_invoice_archetype) else None,
            "ALERT" if (af.missing_tax_id_on_taxed_invoice and r.is_invoice_archetype) else ("N/A" if not r.is_invoice_archetype else "OK"),
            r.average_ocr_confidence,
            needs_review,
            " | ".join(str(n) for n in af.notes if n) if af.notes else "Clean",
            r.file_hash_sha256
        ]
        ws_reg.append(row_data)
        curr_row = ws_reg.max_row

        for c_idx, (_, num_fmt) in enumerate(reg_columns, start=1):
            c_cell = ws_reg.cell(row=curr_row, column=c_idx)
            c_cell.border = thin_border
            if num_fmt and c_cell.value is not None:
                c_cell.number_format = num_fmt

        # Contextual status fills
        status_cell = ws_reg.cell(row=curr_row, column=2)
        if status == "PASSED":
            status_cell.fill, status_cell.font = pass_fill, pass_font
        elif status.startswith("EXCLUDED"):
            status_cell.fill, status_cell.font = warn_fill, warn_font
        else:
            status_cell.fill, status_cell.font = fail_fill, fail_font

        math_cell = ws_reg.cell(row=curr_row, column=16)
        if math_cell.value == "NO":
            math_cell.fill, math_cell.font = fail_fill, fail_font
        elif math_cell.value == "YES":
            math_cell.fill, math_cell.font = pass_fill, pass_font

        trn_cell = ws_reg.cell(row=curr_row, column=19)
        if trn_cell.value == "ALERT":
            trn_cell.fill, trn_cell.font = fail_fill, fail_font

        conf_cell = ws_reg.cell(row=curr_row, column=20)
        if r.quality_passed and r.is_invoice_archetype and r.average_ocr_confidence < CONFIDENCE_THRESHOLD:
            conf_cell.fill, conf_cell.font = triage_fill, triage_font

        review_cell = ws_reg.cell(row=curr_row, column=21)
        if "YES (< 70%" in str(review_cell.value):
            review_cell.fill, review_cell.font = triage_fill, triage_font
        elif "YES (Exception)" in str(review_cell.value):
            review_cell.fill, review_cell.font = warn_fill, warn_font
        elif review_cell.value == "NO":
            review_cell.fill, review_cell.font = pass_fill, pass_font

    # ----------------------------------------------------
    # TAB 3: LINE ITEM DETAIL
    # ----------------------------------------------------
    ws_lines = wb.create_sheet(title="Line_Item_Detail")
    ws_lines.views.sheetView[0].showGridLines = True

    line_columns: List[Tuple[str, Optional[str]]] = [
        ("File Name", None),
        ("Invoice #", None),
        ("Item #", None),
        ("Description", None),
        ("Quantity", "#,##0"),
        ("Inferred Qty?", None),
        ("Unit Price", "#,##0.00"),
        ("Line Total", "#,##0.00"),
        ("Calculated Total (Qty*Rate)", "#,##0.00"),
        ("Line Variance", "#,##0.00"),
        ("Line Math Status", None),
        ("Confidence", "0.0%"),
        ("Manual Check?", None),
        ("Raw OCR Text", None)
    ]

    ws_lines.append([col[0] for col in line_columns])
    for col_idx in range(1, len(line_columns) + 1):
        cell = ws_lines.cell(row=1, column=col_idx)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center", vertical="center")

    all_parsed_items = []
    for r in results:
        if not r.quality_passed or not r.line_items:
            continue
        fname = os.path.basename(r.file_path)
        inv_no = r.header.invoice_number if (r.header and r.header.invoice_number) else "N/A"
        for idx, item in enumerate(r.line_items, start=1):
            status_str = "OK" if item.is_math_sound else "MISMATCH"
            check_flag = "VERIFY (< 70%)" if item.confidence < CONFIDENCE_THRESHOLD else "OK"
            inferred_str = "YES" if item.is_quantity_inferred else "NO"

            row_data = [
                fname,
                inv_no,
                idx,
                item.description,
                item.quantity,
                inferred_str,
                item.unit_price,
                item.line_total,
                item.calculated_total,
                item.line_variance,
                status_str,
                item.confidence,
                check_flag,
                item.raw_text
            ]
            ws_lines.append(row_data)
            curr_row = ws_lines.max_row

            for c_idx, (_, num_fmt) in enumerate(line_columns, start=1):
                c_cell = ws_lines.cell(row=curr_row, column=c_idx)
                c_cell.border = thin_border
                if num_fmt and c_cell.value is not None:
                    c_cell.number_format = num_fmt

            m_cell = ws_lines.cell(row=curr_row, column=11)
            if status_str == "MISMATCH":
                m_cell.fill, m_cell.font = fail_fill, fail_font
            elif item.quantity is not None and item.unit_price is not None:
                m_cell.fill, m_cell.font = pass_fill, pass_font

            c_cell = ws_lines.cell(row=curr_row, column=11)
            chk_cell = ws_lines.cell(row=curr_row, column=12)
            if item.confidence < CONFIDENCE_THRESHOLD:
                c_cell.fill, c_cell.font = triage_fill, triage_font
                chk_cell.fill, chk_cell.font = triage_fill, triage_font
            else:
                chk_cell.fill, chk_cell.font = pass_fill, pass_font

            all_parsed_items.append({
                "invoice_number": inv_no,
                "file_name": fname,
                "description": item.description,
                "norm_desc": normalize_desc(item.description),
                "quantity": item.quantity or 1.0,
                "unit_price": item.unit_price,
                "line_total": item.line_total or 0.0
            })

    # ----------------------------------------------------
    # TAB 4: CROSS-INVOICE PRICE VARIANCE ANALYTICS
    # ----------------------------------------------------
    ws_price = wb.create_sheet(title="Price_Variance_Analytics")
    ws_price.views.sheetView[0].showGridLines = True

    price_columns: List[Tuple[str, Optional[str]]] = [
        ("Item Description", None),
        ("Invoice Count", "#,##0"),
        ("Min Unit Price", "#,##0.00"),
        ("Max Unit Price", "#,##0.00"),
        ("Price Variance", "#,##0.00"),
        ("Variance %", "0.0%"),
        ("Total Quantity", "#,##0"),
        ("Total Spend", "#,##0.00"),
        ("Audit Status", None),
        ("Sample Invoices", None)
    ]

    ws_price.append([col[0] for col in price_columns])
    for col_idx in range(1, len(price_columns) + 1):
        cell = ws_price.cell(row=1, column=col_idx)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center", vertical="center")

    items_by_desc = defaultdict(list)
    for item in all_parsed_items:
        if item["unit_price"] is not None and len(item["norm_desc"]) > 3:
            items_by_desc[item["norm_desc"]].append(item)

    for norm_d, item_list in sorted(items_by_desc.items(), key=lambda x: len(x[1]), reverse=True):
        prices = [it["unit_price"] for it in item_list]
        min_p = min(prices)
        max_p = max(prices)
        diff_p = round(max_p - min_p, 2)
        pct_p = round((diff_p / min_p) * 100.0, 1) if min_p > 0 else 0.0
        tot_qty = sum(it["quantity"] for it in item_list)
        tot_spd = sum(it["line_total"] for it in item_list)
        invs = [str(inv) for inv in set(it["invoice_number"] for it in item_list) if inv and inv != "N/A"]
        sample_invoices = ", ".join(invs[:3]) if invs else "N/A"

        audit_status = "ALERT: PRICE VARIANCE" if diff_p > 0.01 else "CONSISTENT"
        desc_label = item_list[0]["description"]

        row_data = [
            desc_label,
            len(item_list),
            min_p,
            max_p,
            diff_p,
            pct_p / 100.0,
            tot_qty,
            tot_spd,
            audit_status,
            sample_invoices
        ]
        ws_price.append(row_data)
        curr_row = ws_price.max_row

        for c_idx, (_, num_fmt) in enumerate(price_columns, start=1):
            c_cell = ws_price.cell(row=curr_row, column=c_idx)
            c_cell.border = thin_border
            if num_fmt and c_cell.value is not None:
                c_cell.number_format = num_fmt

        stat_cell = ws_price.cell(row=curr_row, column=9)
        if audit_status.startswith("ALERT"):
            stat_cell.fill, stat_cell.font = fail_fill, fail_font
        else:
            stat_cell.fill, stat_cell.font = pass_fill, pass_font

    # ----------------------------------------------------
    # TAB 5: AUDIT EXCEPTIONS QUEUE
    # ----------------------------------------------------
    ws_exc = wb.create_sheet(title="Audit_Exceptions")
    ws_exc.views.sheetView[0].showGridLines = True

    exc_headers = [
        "File Name", "Invoice #", "Exception Type", "Severity",
        "Discrepancy / Value", "Audit Finding & Recommended Action"
    ]
    ws_exc.append(exc_headers)
    for col_idx in range(1, len(exc_headers) + 1):
        cell = ws_exc.cell(row=1, column=col_idx)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center", vertical="center")

    for r in results:
        fname = os.path.basename(r.file_path)
        inv_no = r.header.invoice_number if (r.header and r.header.invoice_number) else "N/A"
        curr = (r.header.currency if r.header and r.header.currency else "USD")

        if not r.quality_passed:
            ws_exc.append([
                fname,
                "N/A",
                "INGESTION_REJECTED",
                "HIGH",
                "Quality Gate Failed",
                " | ".join(str(n) for n in r.audit_flags.notes if n) + " -> Action: Request clean rescan from vendor/department."
            ])
            curr_row = ws_exc.max_row
            ws_exc.cell(row=curr_row, column=4).fill, ws_exc.cell(row=curr_row, column=4).font = fail_fill, fail_font

        elif not r.is_invoice_archetype:
            ws_exc.append([
                fname,
                inv_no,
                "NON_INVOICE_EXCLUSION",
                "INFO",
                r.document_type,
                f"Document classified as '{r.document_type}'. Excluded from accounts payable spend and arithmetic reconciliation."
            ])
            curr_row = ws_exc.max_row
            ws_exc.cell(row=curr_row, column=4).fill, ws_exc.cell(row=curr_row, column=4).font = warn_fill, warn_font

        else:
            if r.audit_flags.math_mismatch_totals:
                ws_exc.append([
                    fname,
                    inv_no,
                    "MATH_TOTALS_MISMATCH",
                    "HIGH",
                    f"{r.audit_flags.totals_discrepancy_amount:,.2f} {curr}",
                    f"Subtotal - Discount + Tax != Total. Discrepancy: {r.audit_flags.totals_discrepancy_amount:,.2f} {curr} -> Action: Audit vendor invoice calculation; withhold payment."
                ])
                curr_row = ws_exc.max_row
                ws_exc.cell(row=curr_row, column=4).fill, ws_exc.cell(row=curr_row, column=4).font = fail_fill, fail_font

            if r.audit_flags.math_mismatch_line_items:
                ws_exc.append([
                    fname,
                    inv_no,
                    "LINE_ITEMS_MISMATCH",
                    "MEDIUM",
                    f"{r.audit_flags.lines_discrepancy_amount:,.2f} {curr}",
                    f"Sum of itemized lines does not equal subtotal. -> Action: Cross-check itemization against ERP Purchase Order."
                ])
                curr_row = ws_exc.max_row
                ws_exc.cell(row=curr_row, column=4).fill, ws_exc.cell(row=curr_row, column=4).font = warn_fill, warn_font

            if r.audit_flags.line_item_calc_mismatches_count > 0:
                ws_exc.append([
                    fname,
                    inv_no,
                    "LINE_MATH_MISMATCH",
                    "HIGH",
                    f"{r.audit_flags.line_item_calc_mismatches_count} Lines",
                    f"Billed line total does not equal Quantity x Unit Price on {r.audit_flags.line_item_calc_mismatches_count} item(s). -> Action: Investigate line item pricing formula."
                ])
                curr_row = ws_exc.max_row
                ws_exc.cell(row=curr_row, column=4).fill, ws_exc.cell(row=curr_row, column=4).font = fail_fill, fail_font

            if r.audit_flags.missing_tax_id_on_taxed_invoice:
                ws_exc.append([
                    fname,
                    inv_no,
                    "TAX_WITHOUT_TRN",
                    "HIGH",
                    f"Tax: {r.totals.tax_amount or 0.0:,.2f} {curr}",
                    "Vendor charged tax/VAT without printing a valid TRN / Tax ID on invoice. -> Action: Disallow VAT input tax credit; request tax compliant invoice."
                ])
                curr_row = ws_exc.max_row
                ws_exc.cell(row=curr_row, column=4).fill, ws_exc.cell(row=curr_row, column=4).font = fail_fill, fail_font

            if r.average_ocr_confidence < CONFIDENCE_THRESHOLD:
                ws_exc.append([
                    fname,
                    inv_no,
                    "LOW_OCR_CONFIDENCE",
                    "MEDIUM",
                    f"{r.average_ocr_confidence * 100.0:.1f}%",
                    f"Average OCR confidence below 70% ({r.average_ocr_confidence * 100.0:.1f}%). -> Action: Manually inspect document image to confirm key accounting figures."
                ])
                curr_row = ws_exc.max_row
                ws_exc.cell(row=curr_row, column=4).fill, ws_exc.cell(row=curr_row, column=4).font = triage_fill, triage_font

    for row in range(2, ws_exc.max_row + 1):
        for col in range(1, len(exc_headers) + 1):
            ws_exc.cell(row=row, column=col).border = thin_border

    # Sample-based column width calculation (avoids iterating 100,000 cells in memory)
    for ws in wb.worksheets:
        max_rows_to_sample = min(ws.max_row, 100)
        for col in ws.iter_cols(min_row=1, max_row=max_rows_to_sample):
            max_len = 0
            col_letter = get_column_letter(col[0].column)
            for cell in col:
                val_str = str(cell.value or "")
                if len(val_str) > max_len and "\n" not in val_str:
                    max_len = len(val_str)
            ws.column_dimensions[col_letter].width = min(max(max_len + 3, 12), 48)

    try:
        wb.save(output_path)
        return output_path
    except PermissionError:
        import datetime
        ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        dir_name = os.path.dirname(output_path)
        base_name = os.path.splitext(os.path.basename(output_path))[0]
        fallback_path = os.path.join(dir_name, f"{base_name}_{ts}.xlsx")
        wb.save(fallback_path)
        print(f"\n[NOTICE] '{output_path}' is locked by Excel. Saved to '{fallback_path}'.")
        return fallback_path
